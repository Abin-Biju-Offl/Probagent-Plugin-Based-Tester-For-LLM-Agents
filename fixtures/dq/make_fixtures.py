"""Create the demo data files in this folder. Synthetic data only.

    python fixtures/dq/make_fixtures.py

Writes:
    orders_clean.csv   200 rows with no issues (random seed 42, so always the same)
    orders_dirty.csv   the same rows with deliberate problems added
    DQ_ISSUES.md       the exact list of those problems (the tests compare against it)
"""

import csv
import random
from datetime import date, timedelta
from pathlib import Path

HERE = Path(__file__).parent
COLUMNS = ["order_id", "email", "quantity", "price", "status", "country", "order_date", "notes"]
NOTES = ["Gift wrap", "Leave at door", "Call before delivery"]

# Each seeded problem: (row, column, new value, expected issue code, why).
# Rows are data rows starting at 1 (the header is not counted).
SEEDED_CHANGES = [
    (12, "email", "john@", "pattern_mismatch", "Email without a domain"),
    (20, "email", "", "missing_value", "Required email is empty"),
    (45, "quantity", "-3", "below_min", "Quantity below 1"),
    (50, "quantity", "five", "wrong_type", "Quantity written as a word"),
    (60, "quantity", "1500", "above_max", "Quantity above 1000"),
    (70, "price", "-5.00", "below_min", "Negative price"),
    (88, "status", "shiped", "not_allowed", "Typo in status"),
    (95, "country", "IND", "too_long", "3-letter country code"),
    (102, "order_id", None, "duplicate_value", "Same order_id as row 67"),
    (110, "order_date", "2026-02-30", "bad_date", "February 30th does not exist"),
    (120, "order_date", "07/10/2026", "wrong_type", "Date in the wrong format"),
    (130, "order_id", "", "missing_value", "Required order_id is empty"),
]
DUPLICATE_OF_ROW = 15          # an exact copy of this row is added at the end
SCRIPT_NOTE_ROW = 140          # a harmless-looking note that tests HTML escaping


def make_clean_rows() -> list[dict]:
    rng = random.Random(42)
    rows = []
    for n in range(1, 201):
        rows.append({
            "order_id": str(1000 + n),
            "email": f"customer{n}@example.com",
            "quantity": str(rng.randint(1, 500)),
            "price": f"{rng.uniform(1, 500):.2f}",
            "status": rng.choice(["pending", "shipped", "cancelled"]),
            "country": rng.choice(["IN", "US", "GB", "DE", "FR"]),
            "order_date": (date(2026, 1, 1) + timedelta(days=rng.randint(0, 89))).isoformat(),
            "notes": rng.choice(NOTES) if rng.random() < 0.15 else "",
        })
    return rows


def make_dirty_rows(clean: list[dict]) -> tuple[list[dict], list[tuple]]:
    rows = [dict(row) for row in clean]
    expected = []
    for row_number, column, value, code, why in SEEDED_CHANGES:
        if code == "duplicate_value":
            value = rows[67 - 1]["order_id"]
        rows[row_number - 1][column] = value
        expected.append((row_number, column, code, why))

    rows[SCRIPT_NOTE_ROW - 1]["notes"] = "Gift wrap <script>alert(1)</script>"

    rows.append(dict(rows[DUPLICATE_OF_ROW - 1]))
    expected.append((len(rows), "-", "duplicate_row", f"Exact copy of row {DUPLICATE_OF_ROW}"))
    return rows, expected


def write_csv(path: Path, rows: list[dict]) -> None:
    with path.open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=COLUMNS)
        writer.writeheader()
        writer.writerows(rows)


def write_issue_list(path: Path, expected: list[tuple]) -> None:
    lines = [
        "# Seeded issues in orders_dirty.csv",
        "",
        "Generated by `make_fixtures.py`. Checking `orders_dirty.csv` with "
        "`orders_rules.json` must report exactly these issues.",
        "Rows are data rows starting at 1 (the header is not counted).",
        "",
        f"Row {SCRIPT_NOTE_ROW} has a `<script>` tag in `notes`. It is **not** an issue: "
        "it checks that the web page shows it as plain text.",
        "",
        "| Row | Column | Code | Why |",
        "|---|---|---|---|",
    ]
    lines += [f"| {row} | {column} | {code} | {why} |" for row, column, code, why in expected]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    clean = make_clean_rows()
    dirty, expected = make_dirty_rows(clean)
    write_csv(HERE / "orders_clean.csv", clean)
    write_csv(HERE / "orders_dirty.csv", dirty)
    write_issue_list(HERE / "DQ_ISSUES.md", expected)
    print(f"Wrote {len(clean)} clean rows, {len(dirty)} dirty rows, {len(expected)} issues.")


if __name__ == "__main__":
    main()
